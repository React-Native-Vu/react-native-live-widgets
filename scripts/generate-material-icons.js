#!/usr/bin/env node

/**
 * Script tự động trích xuất toàn bộ Google Material Icons
 * và sinh ra file type definitions `src/material-icons.generated.ts`
 */

const fs = require('fs');
const path = require('path');

function findGlyphMapPath() {
  const possiblePaths = [
    path.join(__dirname, '..', '..', 'FastdoNative', 'node_modules', '@react-native-vector-icons', 'material-icons', 'glyphmaps', 'MaterialIcons.json'),
    path.join(__dirname, '..', '..', 'FastdoNative', 'node_modules', 'react-native-vector-icons', 'glyphmaps', 'MaterialIcons.json'),
    path.join(__dirname, '..', 'assets', 'MaterialIcons.json'),
  ];

  for (const p of possiblePaths) {
    if (fs.existsSync(p)) {
      return p;
    }
  }
  return null;
}

function generateMaterialIconsFile(outputPath) {
  const glyphPath = findGlyphMapPath();
  let iconNames = [];

  if (glyphPath && fs.existsSync(glyphPath)) {
    try {
      const data = JSON.parse(fs.readFileSync(glyphPath, 'utf8'));
      const set = new Set();
      for (const name of Object.keys(data)) {
        if (!name) continue;
        set.add(name);
        // Hỗ trợ cả snake_case và kebab-case
        if (name.includes('-')) {
          set.add(name.replace(/-/g, '_'));
        }
        if (name.includes('_')) {
          set.add(name.replace(/_/g, '-'));
        }
      }
      iconNames = Array.from(set).sort();
    } catch (err) {
      console.warn('[Material Icons] Lỗi đọc glyphmap:', err.message);
    }
  }

  if (iconNames.length === 0) {
    console.warn('[Material Icons] Không tìm thấy danh sách glyphmap, bỏ qua sinh file.');
    return 0;
  }

  const lines = [
    '/**',
    ' * AUTO-GENERATED BY react-native-live-widgets.',
    ' * Source: Google Material Icons GlyphMap',
    ` * Total icons: ${iconNames.length}`,
    ' * DO NOT EDIT MANUALLY.',
    ' */',
    '',
    'export type KnownMaterialIcon =',
  ];

  for (const name of iconNames) {
    lines.push(`  | '${name}'`);
  }
  lines.push(';');
  lines.push('');

  fs.writeFileSync(outputPath, lines.join('\n'), 'utf8');
  console.log(`🤖 Đã tự động sinh file Material Icons (${iconNames.length} icons) tại: ${path.basename(outputPath)}`);
  return iconNames.length;
}

if (require.main === module) {
  const target = path.join(__dirname, '..', 'src', 'material-icons.generated.ts');
  generateMaterialIconsFile(target);
}

module.exports = {
  generateMaterialIconsFile,
};
