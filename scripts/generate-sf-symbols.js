#!/usr/bin/env node

/**
 * Script tự động trích xuất toàn bộ SF Symbols từ hệ thống Apple
 * và sinh ra file type definitions `src/sf-symbols.generated.ts`
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

function extractSFSymbolsFromSystem() {
  const possiblePaths = [
    '/Applications/SF Symbols.app/Contents/Resources/Metadata/name_availability.plist',
    '/Applications/Xcode.app/Contents/SharedFrameworks/DVTUserInterfaceKit.framework/Resources/SFSymbols/name_availability.plist',
  ];

  for (const plistPath of possiblePaths) {
    if (fs.existsSync(plistPath)) {
      try {
        const jsonStr = execSync(`plutil -convert json -o - "${plistPath}"`, {
          encoding: 'utf8',
          maxBuffer: 50 * 1024 * 1024,
        });
        const data = JSON.parse(jsonStr);
        const symbolsMap = data.symbols || data;
        const names = Object.keys(symbolsMap).filter((name) => Boolean(name) && !name.startsWith('.'));
        if (names.length > 0) {
          names.sort();
          return { symbols: names, source: plistPath };
        }
      } catch (err) {
        console.warn(`[SF Symbols Extract] Error reading ${plistPath}:`, err.message);
      }
    }
  }

  return null;
}

function generateSFSymbolsFile(outputPath, fallbackList = []) {
  let symbols = fallbackList;
  let sourceLabel = 'Fallback Curated List';

  const extracted = extractSFSymbolsFromSystem();
  if (extracted && extracted.symbols.length > 0) {
    symbols = extracted.symbols;
    sourceLabel = extracted.source;
  }

  if (symbols.length === 0) {
    console.warn('[SF Symbols] No symbols found to generate.');
    return;
  }

  const lines = [
    '/**',
    ' * AUTO-GENERATED BY react-native-live-widgets.',
    ` * Source: ${sourceLabel}`,
    ` * Total symbols: ${symbols.length}`,
    ' * DO NOT EDIT MANUALLY.',
    ' */',
    '',
    'export type KnownSFSymbol =',
  ];

  for (const name of symbols) {
    lines.push(`  | '${name}'`);
  }
  lines.push(';');
  lines.push('');

  fs.writeFileSync(outputPath, lines.join('\n'), 'utf8');
  console.log(`✨ Auto-generated SF Symbols (${symbols.length} icons) at: ${path.basename(outputPath)}`);
  return symbols.length;
}

if (require.main === module) {
  const target = path.join(__dirname, '..', 'src', 'sf-symbols.generated.ts');
  generateSFSymbolsFile(target);
}

module.exports = {
  extractSFSymbolsFromSystem,
  generateSFSymbolsFile,
};
